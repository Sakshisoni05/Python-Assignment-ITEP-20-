# 13. Write a  program that keeps a number from the user and generates an integer between 1 and 7 and displays the name of the weekday.
# Test Data
# Input number: 3
# Expected Output :
# Wednesday

num = int(input("Enter a number between 1 and 7: "))

if num ==1 :
    print("MONDAY")
elif num ==2 :
    print("TUESDAY")
elif num==3 :
    print("WEDNESDAY")
elif num==4 :
    print("THRUSDAY")
elif num==5 :
    print("FRIDAY")
elif num==6 :
    print("SATURDAY")
elif num ==7 :
    print("SUNDAY")                    
    
# Q18. Ron jogs around a rectangular park of length 50 m and breadth 30 m. 
# If he takes 10 rounds of the park each day, how much distance does he cover in a day in km?

length = 50 
breadth = 30 
rounds = 10
perimeter = 2 * (length + breadth)

distance = perimeter * rounds

# meter in kilometer
distance_km = distance / 1000

print(f'distance covered : {distance_km} km')


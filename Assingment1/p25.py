# 25. 100 bricks of length 24 cm and breadth 15 cm are used to tile a path of a garden.
#  What is the area of the path?

length = 24
breadth = 15
bricks = 100

# area of one brick ------

brick_area = length * breadth

# area of path -----
area_path = bricks * brick_area

print("Area of the path =", area_path, "cm^2")


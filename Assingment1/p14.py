# Q14. The length of one of the diagonals of a field in the form of a quadrilateral is 46 m. 
# The perpendicular distance of the other two vertices from the diagonal are 13 m and 10 m, 
# find the area of the field.

diagonal = 46
height1 = 13
height2 = 10

area1 = 0.5 *diagonal * height1
area2 = 0.5 *diagonal * height2

total_area = area1 + area2

print(f'Area of the field = {total_area}')
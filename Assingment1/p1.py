# Q1.	 The perimeter of a rectangle is 230 cm. If the length of the rectangle is 70 cm,
#  find its breadth and area.
perimeter = 230
length = 70

# Formula: P = 2(L + B)
breadth = (perimeter / 2) - length

# Formula: Area = L × B
area = length * breadth

print("Breadth =", breadth, "cm")
print("Area =", area, "cm²")
